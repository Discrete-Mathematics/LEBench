#!/usr/bin/env python3
"""Build course/OS_Eval_reduced.c from the unmodified upstream benchmark.

The generated file keeps the authors' timing and K-best code. It drops the
60-second settle, the 96 KB send/recv pair (the upstream comment says it
blocks on older kernels), the 12,000-page fork, and the 10,000-page file
tests. BASE_ITER is scaled down so every booted kernel can be repeated
three times inside one virtual machine. Upstream TEST_DIR/OS_Eval.c is not
modified.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "TEST_DIR" / "OS_Eval.c"
OUTPUT = ROOT / "course" / "OS_Eval_reduced.c"


def wrap(text, start, end, label):
    begin = text.find(start)
    finish = text.find(end, begin if begin >= 0 else 0)
    if begin < 0 or finish < 0 or finish <= begin:
        raise SystemExit("could not find section %s (%s, %s)" % (label, begin, finish))
    return (
        text[:begin]
        + "\n#if 0 /* reduced sweep omits: %s */\n" % label
        + text[begin:finish]
        + "#endif /* %s */\n" % label
        + text[finish:]
    )


def main():
    text = SOURCE.read_text(encoding="utf-8")
    text = text.replace("#define BASE_ITER 10000", "#define BASE_ITER 40", 1)
    old_sleep = "\tsleep(60);\n"
    new_sleep = "\t/* Reduced sweep: the 60-second settle is omitted. */\n"
    if old_sleep not in text:
        raise SystemExit("sleep(60) not found")
    text = text.replace(old_sleep, new_sleep, 1)
    text = text.replace('\tprintf("read: %c\\n", a);\n', "\t(void)a;\n", 1)
    old_result = "\tstruct timespec* result = k_closest[0];\n"
    new_result = (
        "\tstruct timespec* result = k_closest[0];\n"
        "\tif (result == NULL)\n"
        "\t\tresult = &timeArray[0];\n"
    )
    if old_result not in text:
        raise SystemExit("k-best result assignment not found")
    text = text.replace(old_result, new_result, 1)

    text = wrap(
        text,
        "\tmsg_size = 96000;",
        "\t/*****************************************/\n\t/*         FORK & THREAD CREATE",
        "96KB send/recv",
    )
    text = wrap(
        text,
        "\tpage_count = 12000;",
        "\t/*****************************************/\n\t/*     WRITE & READ & MMAP & MUNMAP",
        "12000-page fork",
    )
    text = wrap(
        text,
        "       /****** HUGE ******/",
        "\t/*****************************************/\n\t/*              WRITE & READ",
        "10000-page file tests",
    )

    banner = (
        "/* Generated by course/make_reduced_eval.py from TEST_DIR/OS_Eval.c.\n"
        " * Same measurement functions and K-best rule. Shorter loops, and the\n"
        " * tests named in the #if 0 blocks are not compiled in.\n"
        " */\n"
    )
    OUTPUT.write_text(banner + text, encoding="utf-8")
    print("wrote %s (%d bytes)" % (OUTPUT, OUTPUT.stat().st_size))


if __name__ == "__main__":
    main()
