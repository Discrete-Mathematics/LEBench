#!/usr/bin/env python3
"""Build course/OS_Eval_batched.c from the reduced benchmark.

One change: getpid times GETPID_BATCH calls inside one clock_gettime pair and
divides by that count. Every other test, the K-best rule, and BASE_ITER stay
as in course/OS_Eval_reduced.c. Upstream TEST_DIR/OS_Eval.c is not modified.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "course" / "OS_Eval_reduced.c"
OUTPUT = ROOT / "course" / "OS_Eval_batched.c"

OLD = """void getpid_test(struct timespec *diffTime) {
	struct timespec startTime, endTime;
	clock_gettime(CLOCK_MONOTONIC, &startTime);
	syscall(SYS_getpid);
	clock_gettime(CLOCK_MONOTONIC, &endTime);
	add_diff_to_sum(diffTime, endTime, startTime);
	return;

}"""

NEW = """#define GETPID_BATCH 1000
void getpid_test(struct timespec *diffTime) {
	struct timespec startTime, endTime;
	int batch = GETPID_BATCH;
	static int announced = 0;
	if (!announced) {
		printf("getpid timed as a batch of %d, reported per call.\\n", batch);
		announced = 1;
	}
	clock_gettime(CLOCK_MONOTONIC, &startTime);
	for (int i = 0; i < batch; i++)
		syscall(SYS_getpid);
	clock_gettime(CLOCK_MONOTONIC, &endTime);
	add_diff_to_sum(diffTime, endTime, startTime);
	{
		long long ns = (long long)diffTime->tv_sec * 1000000000LL + diffTime->tv_nsec;
		ns /= batch;
		diffTime->tv_sec = (time_t)(ns / 1000000000LL);
		diffTime->tv_nsec = (long)(ns % 1000000000LL);
	}
	return;

}"""


def main():
    text = SOURCE.read_text(encoding="utf-8")
    if OLD not in text:
        raise SystemExit("getpid_test not found in the reduced source")
    text = text.replace(OLD, NEW, 1)
    banner = (
        "/* Generated by course/make_batched_eval.py from course/OS_Eval_reduced.c.\n"
        " * The only measurement change is getpid: one timed batch, then divide.\n"
        " */\n"
    )
    if text.startswith("/* Generated by course/make_reduced_eval.py"):
        end = text.find("*/\n")
        if end < 0:
            raise SystemExit("reduced banner not closed")
        text = text[end + 3 :]
    OUTPUT.write_text(banner + text, encoding="utf-8")
    print("wrote %s (%d bytes)" % (OUTPUT, OUTPUT.stat().st_size))


if __name__ == "__main__":
    main()
