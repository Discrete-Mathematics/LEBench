#!/usr/bin/env python3
"""Build course/OS_Eval_fulliter.c from the unmodified upstream benchmark.

Same omissions as the reduced suite: the 96 KB send/recv pair, the
12,000-page fork, and the 10,000-page file tests. BASE_ITER stays 10000
and the 60-second settle stays. Upstream TEST_DIR/OS_Eval.c is not modified.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "TEST_DIR" / "OS_Eval.c"
OUTPUT = ROOT / "course" / "OS_Eval_fulliter.c"


def wrap(text, start, end, label):
    begin = text.find(start)
    finish = text.find(end, begin if begin >= 0 else 0)
    if begin < 0 or finish < 0 or finish <= begin:
        raise SystemExit("could not find section %s (%s, %s)" % (label, begin, finish))
    return (
        text[:begin]
        + "\n#if 0 /* full-iter sweep omits: %s */\n" % label
        + text[begin:finish]
        + "#endif /* %s */\n" % label
        + text[finish:]
    )


def main():
    text = SOURCE.read_text(encoding="utf-8")
    if "#define BASE_ITER 10000" not in text:
        raise SystemExit("BASE_ITER 10000 not found")
    text = text.replace('\tprintf("read: %c\\n", a);\n', "\t(void)a;\n", 1)
    old_result = "\tstruct timespec* result = k_closest[0];\n"
    new_result = (
        "\tstruct timespec* result = k_closest[0];\n"
        "\tif (result == NULL)\n"
        "\t\tresult = &timeArray[0];\n"
    )
    if old_result not in text:
        raise SystemExit("k-best result assignment not found")
    text = text.replace(old_result, new_result, 1)
    text = wrap(
        text,
        "\tmsg_size = 96000;",
        "\t/*****************************************/\n\t/*         FORK & THREAD CREATE",
        "96KB send/recv",
    )
    text = wrap(
        text,
        "\tpage_count = 12000;",
        "\t/*****************************************/\n\t/*     WRITE & READ & MMAP & MUNMAP",
        "12000-page fork",
    )
    text = wrap(
        text,
        "       /****** HUGE ******/",
        "\t/*****************************************/\n\t/*              WRITE & READ",
        "10000-page file tests",
    )
    banner = (
        "/* Generated by course/make_full_iter_eval.py from TEST_DIR/OS_Eval.c.\n"
        " * BASE_ITER 10000 and the 60-second settle are the authors' settings.\n"
        " * The tests named in the #if 0 blocks are not compiled in.\n"
        " */\n"
    )
    OUTPUT.write_text(banner + text, encoding="utf-8")
    print("wrote %s (%d bytes)" % (OUTPUT, OUTPUT.stat().st_size))


if __name__ == "__main__":
    main()
